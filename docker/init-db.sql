-- =============================================================================
-- Sample Racking Management System — database schema
-- Idempotent: safe to run on every application startup and as the Postgres
-- container's init script. PostgreSQL 16.
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE SCHEMA IF NOT EXISTS shared;
CREATE SCHEMA IF NOT EXISTS identity;
CREATE SCHEMA IF NOT EXISTS sample_tracking;

-- Row-Level Security helper: reads the tenant id set per-connection by the app.
CREATE OR REPLACE FUNCTION shared.current_tenant_id()
RETURNS UUID AS $$
BEGIN
    RETURN current_setting('app.current_tenant_id', true)::UUID;
EXCEPTION
    WHEN OTHERS THEN
        RETURN NULL;
END;
$$ LANGUAGE plpgsql STABLE;

-- =============================================================================
-- Shared: audit trail
-- =============================================================================
CREATE TABLE IF NOT EXISTS shared.audit_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       UUID NOT NULL,
    user_id         UUID NOT NULL,
    timestamp       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    entity_type     VARCHAR(256) NOT NULL,
    entity_id       UUID NOT NULL,
    action          VARCHAR(64) NOT NULL,
    old_value       JSONB,
    new_value       JSONB,
    source_ip       VARCHAR(45),
    correlation_id  VARCHAR(64),
    module_name     VARCHAR(128) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_audit_log_tenant_entity
    ON shared.audit_log (tenant_id, entity_type, entity_id);
CREATE INDEX IF NOT EXISTS ix_audit_log_timestamp
    ON shared.audit_log (timestamp DESC);

