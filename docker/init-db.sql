-- =============================================================================
-- Sample Tracking module
-- =============================================================================
CREATE SCHEMA IF NOT EXISTS sample_tracking;

-- Rack locations (physical storage positions)
CREATE TABLE IF NOT EXISTS sample_tracking.rack_locations (
    id              UUID PRIMARY KEY,
    tenant_id       UUID NOT NULL,
    code            VARCHAR(50) NOT NULL,
    description     VARCHAR(500),
    zone            VARCHAR(50) NOT NULL,
    level           INT NOT NULL,
    position        INT NOT NULL,
    sort_order      INT NOT NULL,
    capacity        INT NOT NULL DEFAULT 4,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_by      VARCHAR(100) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    modified_by     VARCHAR(100),
    modified_at     TIMESTAMPTZ
);

-- Backfill the capacity column for databases created before it existed.
ALTER TABLE sample_tracking.rack_locations ADD COLUMN IF NOT EXISTS capacity INT NOT NULL DEFAULT 4;

CREATE UNIQUE INDEX IF NOT EXISTS ix_rack_locations_tenant_code
    ON sample_tracking.rack_locations (tenant_id, code);
CREATE INDEX IF NOT EXISTS ix_rack_locations_tenant_active
    ON sample_tracking.rack_locations (tenant_id, is_active);

-- Samples (aggregate root)
CREATE TABLE IF NOT EXISTS sample_tracking.samples (
    id                      UUID PRIMARY KEY,
    tenant_id               UUID NOT NULL,
    sample_code             VARCHAR(50) NOT NULL,
    sample_name             VARCHAR(200) NOT NULL,
    item_code               VARCHAR(100),
    product_category        VARCHAR(100),
    model                   VARCHAR(100),
    size                    VARCHAR(100),
    variant                 VARCHAR(100),
    material_type           VARCHAR(100),
    supplier_name           VARCHAR(200),
    supplier_code           VARCHAR(100),
    purchase_order_number   VARCHAR(100),
    grn_number              VARCHAR(100),
    supplier_reference      VARCHAR(200),
    received_date           DATE NOT NULL,
    received_time           TIME,
    received_quantity       NUMERIC(18,2) NOT NULL DEFAULT 1,
    received_by             VARCHAR(150),
    department              VARCHAR(150),
    sample_owner            VARCHAR(150),
    description             VARCHAR(2000),
    purpose                 VARCHAR(1000),
    testing_requirement     VARCHAR(1000),
    required_testing_type   VARCHAR(150),
    storage_remarks         VARCHAR(1000),
    rack_location_id        UUID REFERENCES sample_tracking.rack_locations(id) ON DELETE SET NULL,
    status                  VARCHAR(50) NOT NULL DEFAULT 'Received',
    created_by              VARCHAR(100) NOT NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    modified_by             VARCHAR(100),
    modified_at             TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_samples_tenant_code
    ON sample_tracking.samples (tenant_id, sample_code);
CREATE INDEX IF NOT EXISTS ix_samples_tenant_status
    ON sample_tracking.samples (tenant_id, status);
CREATE INDEX IF NOT EXISTS ix_samples_tenant_location
    ON sample_tracking.samples (tenant_id, rack_location_id);
CREATE INDEX IF NOT EXISTS ix_samples_tenant_received
    ON sample_tracking.samples (tenant_id, received_date);

-- Status history (append-only)
CREATE TABLE IF NOT EXISTS sample_tracking.sample_status_history (
    id              UUID PRIMARY KEY,
    tenant_id       UUID NOT NULL,
    sample_id       UUID NOT NULL REFERENCES sample_tracking.samples(id) ON DELETE CASCADE,
    previous_status VARCHAR(50),
    new_status      VARCHAR(50) NOT NULL,
    changed_by      VARCHAR(150) NOT NULL,
    changed_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reason          VARCHAR(500),
    remarks         VARCHAR(1000)
);
CREATE INDEX IF NOT EXISTS ix_sample_status_history_sample
    ON sample_tracking.sample_status_history (sample_id);

-- Movement history
CREATE TABLE IF NOT EXISTS sample_tracking.sample_movements (
    id                  UUID PRIMARY KEY,
    tenant_id           UUID NOT NULL,
    sample_id           UUID NOT NULL REFERENCES sample_tracking.samples(id) ON DELETE CASCADE,
    from_location_id    UUID,
    from_location_code  VARCHAR(50),
    to_location_id      UUID NOT NULL,
    to_location_code    VARCHAR(50) NOT NULL,
    moved_by            VARCHAR(150) NOT NULL,
    moved_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reason              VARCHAR(500),
    remarks             VARCHAR(1000)
);
CREATE INDEX IF NOT EXISTS ix_sample_movements_sample
    ON sample_tracking.sample_movements (sample_id);
CREATE INDEX IF NOT EXISTS ix_sample_movements_tenant_moved
    ON sample_tracking.sample_movements (tenant_id, moved_at);

-- Testing records
CREATE TABLE IF NOT EXISTS sample_tracking.testing_records (
    id                      UUID PRIMARY KEY,
    tenant_id               UUID NOT NULL,
    sample_id               UUID NOT NULL REFERENCES sample_tracking.samples(id) ON DELETE CASCADE,
    testing_type            VARCHAR(150) NOT NULL,
    testing_standard        VARCHAR(200),
    testing_date            TIMESTAMPTZ NOT NULL,
    tested_by               VARCHAR(150) NOT NULL,
    result                  VARCHAR(20) NOT NULL,
    remarks                 VARCHAR(1000),
    defect_description      VARCHAR(2000),
    photo_evidence_ref      VARCHAR(500),
    report_attachment_ref   VARCHAR(500),
    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_testing_records_sample
    ON sample_tracking.testing_records (sample_id);

-- Attachments (metadata; binaries live in object storage)
CREATE TABLE IF NOT EXISTS sample_tracking.sample_attachments (
    id              UUID PRIMARY KEY,
    tenant_id       UUID NOT NULL,
    sample_id       UUID NOT NULL REFERENCES sample_tracking.samples(id) ON DELETE CASCADE,
    file_name       VARCHAR(300) NOT NULL,
    file_ref        VARCHAR(500) NOT NULL,
    content_type    VARCHAR(150),
    size_bytes      BIGINT,
    category        VARCHAR(30) NOT NULL,
    uploaded_by     VARCHAR(150) NOT NULL,
    uploaded_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_sample_attachments_sample
    ON sample_tracking.sample_attachments (sample_id);

-- Disposal records (one per sample)
CREATE TABLE IF NOT EXISTS sample_tracking.disposal_records (
    id              UUID PRIMARY KEY,
    tenant_id       UUID NOT NULL,
    sample_id       UUID NOT NULL REFERENCES sample_tracking.samples(id) ON DELETE CASCADE,
    reason          VARCHAR(1000) NOT NULL,
    requested_by    VARCHAR(150) NOT NULL,
    requested_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    approval_status VARCHAR(20) NOT NULL DEFAULT 'Pending',
    approved_by     VARCHAR(150),
    approved_at     TIMESTAMPTZ,
    disposal_date   DATE,
    remarks         VARCHAR(1000)
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_disposal_records_sample
    ON sample_tracking.disposal_records (sample_id);

-- Notifications
CREATE TABLE IF NOT EXISTS sample_tracking.notifications (
    id              UUID PRIMARY KEY,
    tenant_id       UUID NOT NULL,
    type            VARCHAR(50) NOT NULL,
    severity        VARCHAR(20) NOT NULL,
    title           VARCHAR(300) NOT NULL,
    message         VARCHAR(1000) NOT NULL,
    sample_id       UUID,
    sample_code     VARCHAR(50),
    dedupe_key      VARCHAR(200),
    is_read         BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    read_at         TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_notifications_tenant_read
    ON sample_tracking.notifications (tenant_id, is_read);
CREATE INDEX IF NOT EXISTS ix_notifications_tenant_created
    ON sample_tracking.notifications (tenant_id, created_at);
CREATE INDEX IF NOT EXISTS ix_notifications_dedupe
    ON sample_tracking.notifications (dedupe_key);

-- Per-tenant settings (one row per tenant)
CREATE TABLE IF NOT EXISTS sample_tracking.settings (
    id                      UUID PRIMARY KEY,
    tenant_id               UUID NOT NULL,
    company_name            VARCHAR(200),
    department_name         VARCHAR(200),
    sample_id_prefix        VARCHAR(10) NOT NULL DEFAULT 'SMP',
